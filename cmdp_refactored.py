#!/usr/bin/env python3
"""
Refactored CMDP terrain/planning pipeline.

This is a structural refactor of the supplied notebook:
    OBJ -> terrain grid -> terrain features -> risk -> CMDP -> path -> analysis

Notebook-only diagnostics, repeated reloads, plots, and exploratory print
blocks have been removed. The research calculations are kept in functions
so that the same code can be reused for different terrain/configurations.

Important:
- Terrain IDs: rock=0, mud=1, water=2, wall=3
- Terrain risk: rock=0.0, mud=0.25, water=1.0. Wall cells (id 3) have NO
  terrain-risk value, so their weighted risk is NaN, i.e. they are
  non-traversable for the CMDP solver and for RRT*.
- The Step 8 weights are (slope, roughness, terrain, clearance) =
  (0.30, 0.15, 0.40, 0.15).
- OBJ objects are classified BY NAME: terrain_rock, mud_*, water_*, wall*.
  Blender "Y up" exports are detected and converted to Z up automatically.
- The Step 11A solver preserves the supplied notebook's 2-D movement-cost
  calculation. Step 2's standalone helper still supports the notebook's
  3-D geometric movement cost.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np


# Optional dependencies are imported only when the corresponding step runs.
# This keeps the CMDP solver usable without trimesh/matplotlib.
GridState = Tuple[int, int]


TERRAIN_NAMES = {
    0: "rock",
    1: "mud",
    2: "water",
    3: "wall",
}

WALL_ID = 3

# Bump this whenever the terrain_grid.json content/meaning changes, so the
# runners can detect (and regenerate) stale files.
TERRAIN_GRID_SCHEMA_VERSION = 2

DEFAULT_RISK_WEIGHTS = (0.30, 0.15, 0.40, 0.15)  # (slope, rough, terrain, clearance)

TERRAIN_RISK_VALUES = {
    0: 0.0,
    1: 0.5,
    2: 1.0,
}

ACTIONS = {
    0: (-1, -1),
    1: (-1, 0),
    2: (-1, 1),
    3: (0, -1),
    4: (0, 1),
    5: (1, -1),
    6: (1, 0),
    7: (1, 1),
}


@dataclass
class TerrainData:
    """All reusable terrain/grid data produced before CMDP solving."""

    grid: np.ndarray
    height_grid: np.ndarray
    coverage_grid: np.ndarray
    resolution: float
    bounds: Dict[str, float]

    @property
    def shape(self) -> Tuple[int, int]:
        return self.grid.shape

    @property
    def nx(self) -> int:
        return self.grid.shape[0]

    @property
    def ny(self) -> int:
        return self.grid.shape[1]

    @property
    def valid_terrain_mask(self) -> np.ndarray:
        return np.isfinite(self.height_grid)

    @property
    def wall_mask(self) -> np.ndarray:
        return self.grid == WALL_ID


@dataclass
class RiskFeatures:
    """Risk features calculated from the terrain."""

    slope_deg: np.ndarray
    roughness_grid: np.ndarray
    terrain_risk_grid: np.ndarray
    clearance_grid: np.ndarray

    S_risk: np.ndarray
    R_risk: np.ndarray
    T_risk: np.ndarray
    C_risk: np.ndarray

    weighted_risk_grid: np.ndarray
    valid_risk_features: np.ndarray


@dataclass
class CMDPResult:
    """Result returned by the constrained CMDP solver."""

    V: np.ndarray
    policy: np.ndarray
    lambda_value: float
    expected_cost: float
    expected_risk: float
    constraint_satisfied: bool


@dataclass
class PathResult:
    """Path generated by following a CMDP policy."""

    path_grid: List[GridState]
    path_world: np.ndarray
    reached_goal: bool
    total_path_length: float


