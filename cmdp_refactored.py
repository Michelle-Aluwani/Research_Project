def _parse_grid_state(value: str) -> GridState:
    try:
        x, y = value.split(",")
        return int(x), int(y)
    except Exception as exc:
        raise argparse.ArgumentTypeError(
            "Expected coordinate as x,y"
        ) from exc


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Run the refactored CMDP terrain pipeline."
    )
    parser.add_argument(
        "--terrain-grid",
        type=Path,
        required=True,
        help="Existing terrain_grid.json",
    )
    parser.add_argument(
        "--start",
        type=_parse_grid_state,
        required=True,
        help="Grid start coordinate, e.g. 30,100",
    )
    parser.add_argument(
        "--goal",
        type=_parse_grid_state,
        required=True,
        help="Grid goal coordinate, e.g. 146,91",
    )
    parser.add_argument(
        "--D",
        type=float,
        required=True,
        dest="risk_budget",
        help="CMDP risk budget",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("cmdp_result.json"),
    )
    parser.add_argument(
        "--path-output",
        type=Path,
        default=Path("cmdp_path_world.csv"),
    )
    parser.add_argument(
        "--backend",
        choices=("auto", "numpy", "torch"),
        default="auto",
        help="Solver backend: auto uses CUDA when available, otherwise NumPy.",
    )
    parser.add_argument(
        "--device",
        default=None,
        help="PyTorch device, e.g. cuda, cuda:0, or cpu.",
    )

    args = parser.parse_args()

    terrain = load_terrain_grid(args.terrain_grid)

    result = run_experiment(
        terrain=terrain,
        start=args.start,
        goal=args.goal,
        risk_budget=args.risk_budget,
        output_path=args.output,
        backend=args.backend,
        device=args.device,
        path_output=args.path_output,
    )

    print(json.dumps(result, indent=2))

    # A CMDP that cannot reach the goal is a valid experimental outcome, not
    # a crash: cmdp_result.json is written (reached_goal = false) and no
    # path CSV is produced. Exit code 2 tells the runner "no path".
    if not result["reached_goal"]:
        print("CMDP did not reach the goal; no path CSV written.")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
