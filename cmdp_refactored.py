def risk_statistics(weighted_risk_grid: np.ndarray) -> Dict[str, float]:
    """Return the risk statistics used for inspection/analysis."""
    valid = weighted_risk_grid[np.isfinite(weighted_risk_grid)]
    if len(valid) == 0:
        raise ValueError("No finite risk values are available.")

    return {
        "minimum": float(np.min(valid)),
        "maximum": float(np.max(valid)),
        "mean": float(np.mean(valid)),
        "median": float(np.median(valid)),
        "p25": float(np.percentile(valid, 25)),
        "p50": float(np.percentile(valid, 50)),
        "p75": float(np.percentile(valid, 75)),
        "p90": float(np.percentile(valid, 90)),
    }


# ---------------------------------------------------------------------------
# STEP 10B — START / GOAL SELECTION
# ---------------------------------------------------------------------------

def direct_route_cells(
    start: GridState,
    goal: GridState,
) -> List[GridState]:
    """Sample grid cells along the direct start-goal line."""
    x1, y1 = start
    x2, y2 = goal
    distance = np.hypot(x2 - x1, y2 - y1)
    samples = int(np.ceil(distance)) + 1

    xs = np.rint(np.linspace(x1, x2, samples)).astype(int)
    ys = np.rint(np.linspace(y1, y2, samples)).astype(int)

    return list(dict.fromkeys(zip(xs, ys)))


def route_contains_mud_and_water(
    terrain: TerrainData,
    start: GridState,
    goal: GridState,
) -> Tuple[bool, List[GridState]]:
    """Check whether a direct route contains both mud and water."""
    cells = direct_route_cells(start, goal)
    terrain_ids = np.array(
        [terrain.grid[x, y] for x, y in cells],
        dtype=np.int8,
    )
    return (
        np.any(terrain_ids == 1) and np.any(terrain_ids == 2),
        cells,
    )


def select_start_goal(
    terrain: TerrainData,
    weighted_risk_grid: np.ndarray,
    min_separation: int = 80,
    num_pairs: int = 10_000,
    rng_seed: int = 42,
) -> Tuple[GridState, GridState]:
    """Select the notebook's rock-to-rock pair crossing mud and water."""
    rng = np.random.default_rng(rng_seed)

    rock_cells = np.argwhere(terrain.grid == 0)
    left_rock = rock_cells[rock_cells[:, 0] < terrain.nx * 0.25]
    right_rock = rock_cells[rock_cells[:, 0] > terrain.nx * 0.75]

    if len(left_rock) == 0 or len(right_rock) == 0:
        raise RuntimeError(
            "Not enough rock cells on opposite sides of the map."
        )

    valid_pairs = []

    for _ in range(num_pairs):
        start = tuple(
            map(int, left_rock[rng.integers(len(left_rock))])
        )
        goal = tuple(
            map(int, right_rock[rng.integers(len(right_rock))])
        )

        separation = np.hypot(
            goal[0] - start[0],
            goal[1] - start[1],
        )

        if separation < min_separation:
            continue

        contains_both, route = route_contains_mud_and_water(
            terrain, start, goal
        )
        if not contains_both:
            continue

        route_terrain = np.array(
            [terrain.grid[x, y] for x, y in route]
        )
        mud_count = int(np.sum(route_terrain == 1))
        water_count = int(np.sum(route_terrain == 2))
        score = mud_count + water_count

        valid_pairs.append(
            (
                score,
                separation,
                start,
                goal,
                mud_count,
                water_count,
            )
        )

    if not valid_pairs:
        raise RuntimeError(
            "No start/goal pair found whose direct route crosses both "
            "mud and water."
        )

    valid_pairs.sort(key=lambda p: (p[0], p[1]), reverse=True)
    _, _, start, goal, _, _ = valid_pairs[0]

    if not np.isfinite(weighted_risk_grid[start]):
        raise ValueError("Selected start has invalid risk.")
    if not np.isfinite(weighted_risk_grid[goal]):
        raise ValueError("Selected goal has invalid risk.")

    return start, goal


# ---------------------------------------------------------------------------
# STEP 11A — CONSTRAINED CMDP SOLVER
# ---------------------------------------------------------------------------

class CMDPSolver:
    """CMDP solver with the same Step 11A logic, using vectorized execution.

    The Bellman/value-iteration equations, action set, movement cost,
    stochastic model, lambda search, stopping criteria, and policy evaluation
    are unchanged. The difference is that the state/action loops are replaced
    by array operations. With ``backend="torch"`` and a CUDA device, these
    arrays can live on an NVIDIA GPU.

    Backends:
        ``"auto"``   -> CUDA if available, otherwise NumPy
        ``"numpy"``  -> vectorized CPU implementation
        ``"torch"``  -> PyTorch; CUDA if available, otherwise CPU
    """

    def __init__(
        self,
        terrain: TerrainData,
        weighted_risk_grid: np.ndarray,
        start: GridState,
        goal: GridState,
        initial_lambda: float = 0.25,
        max_lambda: float = 100.0,
        max_lambda_iterations: int = 30,
        tolerance: float = 1e-6,
        max_iterations: int = 1000,
        backend: str = "auto",
        device: Optional[str] = None,
    ):
        self.terrain = terrain
        self.weighted_risk_grid = np.asarray(weighted_risk_grid, dtype=np.float64)
        self.start = tuple(start)
        self.goal = tuple(goal)

        self.grid_width, self.grid_height = self.weighted_risk_grid.shape
        self.grid_resolution = terrain.resolution

        self.initial_lambda = initial_lambda
        self.max_lambda = max_lambda
        self.max_lambda_iterations = max_lambda_iterations
        self.tolerance = tolerance
        self.max_iterations = max_iterations

        self.backend, self.device = self._select_backend(backend, device)
        self._prepare_vectorized_model()

    @staticmethod
    def _select_backend(backend: str, device: Optional[str]):
        backend = backend.lower()
        if backend not in {"auto", "numpy", "torch"}:
            raise ValueError("backend must be 'auto', 'numpy', or 'torch'.")

        if backend == "numpy":
            return "numpy", "cpu"

        if backend == "torch":
            import torch
            if device is None:
                device = "cuda" if torch.cuda.is_available() else "cpu"
            return "torch", device

        # auto
        try:
            import torch
            if torch.cuda.is_available():
                return "torch", device or "cuda"
        except ImportError:
            pass
        return "numpy", "cpu"

    def _movement_cost(self, action_id: int) -> float:
        """Preserve Step 11A's 2-D movement cost."""
        dx, dy = ACTIONS[action_id]
        if dx != 0 and dy != 0:
            return self.grid_resolution * math.sqrt(2.0)
        return self.grid_resolution

    def _prepare_vectorized_model(self) -> None:
        """Precompute the fixed 8-neighbour transition structure once."""
        n_states = self.grid_width * self.grid_height
        valid_destination = np.isfinite(self.weighted_risk_grid).reshape(-1)

        next_index = np.full((8, n_states), -1, dtype=np.int64)
        action_cost = np.empty(8, dtype=np.float64)

        for action_id, (dx, dy) in ACTIONS.items():
            action_cost[action_id] = self._movement_cost(action_id)

            # State index is x * grid_height + y, matching the flattened
            # C-order representation of the original (x, y) arrays.
            xs = np.arange(self.grid_width)[:, None]
            ys = np.arange(self.grid_height)[None, :]
            nx = np.broadcast_to(xs + dx, (self.grid_width, self.grid_height))
            ny = np.broadcast_to(ys + dy, (self.grid_width, self.grid_height))
            valid = (
                (nx >= 0)
                & (nx < self.grid_width)
                & (ny >= 0)
                & (ny < self.grid_height)
            )
            destination = np.full((self.grid_width, self.grid_height), -1, dtype=np.int64)
            destination[valid] = (
                nx[valid] * self.grid_height + ny[valid]
            )
            destination_flat = destination.reshape(-1)
            valid &= valid_destination[destination_flat.clip(min=0)].reshape(
                self.grid_width, self.grid_height
            )
            destination_flat[~valid.reshape(-1)] = -1
            next_index[action_id] = destination_flat

        self._next_index_np = next_index
        self._action_cost_np = action_cost
        self._valid_state_np = valid_destination

        if self.backend == "torch":
            import torch
            self._next_index = torch.as_tensor(
                next_index, dtype=torch.long, device=self.device
            )
            self._action_cost = torch.as_tensor(
                action_cost, dtype=torch.float64, device=self.device
            )
            self._risk = torch.as_tensor(
                self.weighted_risk_grid.reshape(-1),
                dtype=torch.float64,
                device=self.device,
            )
        else:
            self._next_index = next_index
            self._action_cost = action_cost
            self._risk = self.weighted_risk_grid.reshape(-1)

        self._goal_index = self.goal[0] * self.grid_height + self.goal[1]

    def _solve_lagrangian_numpy(
        self,
        lambda_value: float,
    ) -> Tuple[np.ndarray, np.ndarray]:
        """Vectorized NumPy implementation of the original Step 11A loop."""
        n = self.grid_width * self.grid_height
        V = np.full(n, np.inf, dtype=np.float64)
        policy = np.full(n, -1, dtype=np.int8)
        V[self._goal_index] = 0.0

        for _ in range(self.max_iterations):
            old_V = V.copy()

            destination_indices = self._next_index_np
            valid = destination_indices >= 0
            safe_indices = np.maximum(destination_indices, 0)

            destination_risk = self._risk[safe_indices]
            destination_value = old_V[safe_indices]

            finite_destination = np.isfinite(destination_risk)
            finite_value = np.isfinite(destination_value)
            usable = valid & finite_destination & finite_value

            clipped_risk = np.clip(destination_risk, 0.0, 1.0)
            p_success = 1.0 - clipped_risk
            usable &= p_success > 0.0

            immediate = (
                self._action_cost_np[:, None]
                + lambda_value * clipped_risk
            )
            candidates = np.full((8, n), np.inf, dtype=np.float64)
            candidates[usable] = (
                immediate[usable] + p_success[usable] * destination_value[usable]
            ) / p_success[usable]

            # np.argmin returns the first minimum, preserving the original
            # ACTIONS insertion order when candidate values are tied.
            best_action = np.argmin(candidates, axis=0).astype(np.int8)
            best_value = np.min(candidates, axis=0)
            reachable = np.isfinite(best_value)

            V = best_value
            policy = np.where(reachable, best_action, -1).astype(np.int8)
            V[self._goal_index] = 0.0
            policy[self._goal_index] = -1

            newly_reached = np.any(~np.isfinite(old_V) & np.isfinite(V))
            finite_both = np.isfinite(old_V) & np.isfinite(V)
            if np.any(finite_both):
                max_change = np.max(np.abs(V[finite_both] - old_V[finite_both]))
            else:
                max_change = 0.0

            if max_change < self.tolerance and not newly_reached:
                break

        return (
            V.reshape(self.grid_width, self.grid_height),
            policy.reshape(self.grid_width, self.grid_height),
        )

    def _solve_lagrangian_torch(
        self,
        lambda_value: float,
    ) -> Tuple[np.ndarray, np.ndarray]:
        """Vectorized PyTorch implementation; runs on CUDA when selected."""
        import torch

        n = self.grid_width * self.grid_height
        inf = float("inf")
        V = torch.full((n,), inf, dtype=torch.float64, device=self.device)
        policy = torch.full((n,), -1, dtype=torch.int8, device=self.device)
        V[self._goal_index] = 0.0

        for _ in range(self.max_iterations):
            old_V = V.clone()

            destination_indices = self._next_index
            valid = destination_indices >= 0
            safe_indices = torch.clamp(destination_indices, min=0)

            destination_risk = self._risk[safe_indices]
            destination_value = old_V[safe_indices]

            finite_destination = torch.isfinite(destination_risk)
            finite_value = torch.isfinite(destination_value)
            usable = valid & finite_destination & finite_value

            clipped_risk = torch.clamp(destination_risk, 0.0, 1.0)
            p_success = 1.0 - clipped_risk
            usable = usable & (p_success > 0.0)

            immediate = (
                self._action_cost[:, None]
                + lambda_value * clipped_risk
            )
            candidates = torch.full(
                (8, n), inf, dtype=torch.float64, device=self.device
            )
            candidates = torch.where(
                usable,
                (immediate + p_success * destination_value) / p_success,
                candidates,
            )

            best_value, best_action = torch.min(candidates, dim=0)
            reachable = torch.isfinite(best_value)

            V = torch.where(reachable, best_value, torch.full_like(best_value, inf))
            policy = torch.where(
                reachable,
                best_action.to(torch.int8),
                torch.full_like(policy, -1),
            )
            V[self._goal_index] = 0.0
            policy[self._goal_index] = -1

            newly_reached = torch.any(~torch.isfinite(old_V) & torch.isfinite(V)).item()
            finite_both = torch.isfinite(old_V) & torch.isfinite(V)
            if torch.any(finite_both).item():
                max_change = torch.max(
                    torch.abs(V[finite_both] - old_V[finite_both])
                ).item()
            else:
                max_change = 0.0

            if max_change < self.tolerance and not newly_reached:
                break

        return (
            V.reshape(self.grid_width, self.grid_height).detach().cpu().numpy(),
            policy.reshape(self.grid_width, self.grid_height).detach().cpu().numpy(),
        )

    def solve_lagrangian_value_iteration(
        self,
        lambda_value: float,
    ) -> Tuple[np.ndarray, np.ndarray]:
        """Solve fixed-lambda Step 11A using a vectorized backend."""
        if self.backend == "torch":
            return self._solve_lagrangian_torch(lambda_value)
        return self._solve_lagrangian_numpy(lambda_value)

    def _evaluate_policy_numpy(
        self,
        policy: np.ndarray,
    ) -> Tuple[float, float]:
        """Vectorized NumPy implementation of the original policy evaluation."""
        n = self.grid_width * self.grid_height
        policy_flat = np.asarray(policy, dtype=np.int8).reshape(-1)

        V_cost = np.full(n, np.inf, dtype=np.float64)
        V_risk = np.full(n, np.inf, dtype=np.float64)
        V_cost[self._goal_index] = 0.0
        V_risk[self._goal_index] = 0.0

        for _ in range(self.max_iterations):
            old_cost = V_cost.copy()
            old_risk = V_risk.copy()

            safe_actions = np.clip(policy_flat.astype(np.int16), 0, 7)
            state_indices = self._next_index_np[safe_actions, np.arange(n)]
            valid_action = policy_flat >= 0
            valid_action &= state_indices >= 0
            safe_indices = np.maximum(state_indices, 0)

            destination_risk = self._risk[safe_indices]
            finite_destination = np.isfinite(destination_risk)
            finite_values = (
                np.isfinite(old_cost[safe_indices])
                & np.isfinite(old_risk[safe_indices])
            )
            usable = valid_action & finite_destination & finite_values

            clipped_risk = np.clip(destination_risk, 0.0, 1.0)
            p_success = 1.0 - clipped_risk
            usable &= p_success > 0.0

            movement_cost = self._action_cost_np[safe_actions]
            new_cost = np.full(n, np.inf, dtype=np.float64)
            new_risk = np.full(n, np.inf, dtype=np.float64)

            new_cost[usable] = (
                movement_cost[usable]
                + p_success[usable] * old_cost[safe_indices[usable]]
            ) / p_success[usable]
            new_risk[usable] = (
                clipped_risk[usable]
                + p_success[usable] * old_risk[safe_indices[usable]]
            ) / p_success[usable]

            finite_new = np.isfinite(new_cost) & np.isfinite(new_risk)
            V_cost = new_cost
            V_risk = new_risk
            V_cost[self._goal_index] = 0.0
            V_risk[self._goal_index] = 0.0

            newly_reached_cost = np.any(~np.isfinite(old_cost) & np.isfinite(V_cost))
            newly_reached_risk = np.any(~np.isfinite(old_risk) & np.isfinite(V_risk))
            finite_both = finite_new & np.isfinite(old_cost) & np.isfinite(old_risk)
            if np.any(finite_both):
                max_change = max(
                    np.max(np.abs(V_cost[finite_both] - old_cost[finite_both])),
                    np.max(np.abs(V_risk[finite_both] - old_risk[finite_both])),
                )
            else:
                max_change = 0.0

            if (
                max_change < self.tolerance
                and not newly_reached_cost
                and not newly_reached_risk
            ):
                break

        sx, sy = self.start
        start_index = sx * self.grid_height + sy
        return float(V_cost[start_index]), float(V_risk[start_index])

    def _evaluate_policy_torch(
        self,
        policy: np.ndarray,
    ) -> Tuple[float, float]:
        """Vectorized PyTorch policy evaluation."""
        import torch

        n = self.grid_width * self.grid_height
        policy_tensor = torch.as_tensor(
            np.asarray(policy, dtype=np.int8).reshape(-1),
            dtype=torch.int64,
            device=self.device,
        )

        V_cost = torch.full((n,), float("inf"), dtype=torch.float64, device=self.device)
        V_risk = torch.full((n,), float("inf"), dtype=torch.float64, device=self.device)
        V_cost[self._goal_index] = 0.0
        V_risk[self._goal_index] = 0.0

        state_indices_all = torch.arange(n, dtype=torch.long, device=self.device)

        for _ in range(self.max_iterations):
            old_cost = V_cost.clone()
            old_risk = V_risk.clone()

            safe_actions = torch.clamp(policy_tensor, 0, 7)
            state_indices = self._next_index[safe_actions, state_indices_all]
            valid_action = policy_tensor >= 0
            valid_action = valid_action & (state_indices >= 0)
            safe_indices = torch.clamp(state_indices, min=0)

            destination_risk = self._risk[safe_indices]
            finite_destination = torch.isfinite(destination_risk)
            finite_values = (
                torch.isfinite(old_cost[safe_indices])
                & torch.isfinite(old_risk[safe_indices])
            )
            usable = valid_action & finite_destination & finite_values

            clipped_risk = torch.clamp(destination_risk, 0.0, 1.0)
            p_success = 1.0 - clipped_risk
            usable = usable & (p_success > 0.0)

            movement_cost = self._action_cost[safe_actions]
            new_cost = torch.full_like(V_cost, float("inf"))
            new_risk = torch.full_like(V_risk, float("inf"))

            computed_cost = (
                movement_cost
                + p_success * old_cost[safe_indices]
            ) / p_success
            computed_risk = (
                clipped_risk
                + p_success * old_risk[safe_indices]
            ) / p_success

            new_cost = torch.where(usable, computed_cost, new_cost)
            new_risk = torch.where(usable, computed_risk, new_risk)
            V_cost = new_cost
            V_risk = new_risk
            V_cost[self._goal_index] = 0.0
            V_risk[self._goal_index] = 0.0

            newly_reached_cost = torch.any(
                ~torch.isfinite(old_cost) & torch.isfinite(V_cost)
            ).item()
            newly_reached_risk = torch.any(
                ~torch.isfinite(old_risk) & torch.isfinite(V_risk)
            ).item()

            finite_both = (
                torch.isfinite(V_cost)
                & torch.isfinite(V_risk)
                & torch.isfinite(old_cost)
                & torch.isfinite(old_risk)
            )
            if torch.any(finite_both).item():
                max_change = max(
                    torch.max(torch.abs(V_cost[finite_both] - old_cost[finite_both])).item(),
                    torch.max(torch.abs(V_risk[finite_both] - old_risk[finite_both])).item(),
                )
            else:
                max_change = 0.0

            if (
                max_change < self.tolerance
                and not newly_reached_cost
                and not newly_reached_risk
            ):
                break

        sx, sy = self.start
        start_index = sx * self.grid_height + sy
        return float(V_cost[start_index].item()), float(V_risk[start_index].item())

    def evaluate_policy(
        self,
        policy: np.ndarray,
    ) -> Tuple[float, float]:
        """Evaluate a policy with the selected vectorized backend."""
        if self.backend == "torch":
            return self._evaluate_policy_torch(policy)
        return self._evaluate_policy_numpy(policy)

    def solve_constrained_cmdp(
        self,
        risk_budget: float,
    ) -> CMDPResult:
        """Find the smallest feasible lambda using the original search logic."""
        lambda_value = self.initial_lambda

        V, policy = self.solve_lagrangian_value_iteration(lambda_value)
        expected_cost, expected_risk = self.evaluate_policy(policy)

        if (
            np.isfinite(expected_risk)
            and expected_risk <= risk_budget
        ):
            return CMDPResult(
                V=V,
                policy=policy,
                lambda_value=lambda_value,
                expected_cost=expected_cost,
                expected_risk=expected_risk,
                constraint_satisfied=True,
            )

        lower_lambda = lambda_value
        upper_lambda = lambda_value
        found_feasible = False

        V_test = V
        policy_test = policy
        cost_test = expected_cost
        risk_test = expected_risk

        for _ in range(self.max_lambda_iterations):
            V_test, policy_test = self.solve_lagrangian_value_iteration(
                upper_lambda
            )
            cost_test, risk_test = self.evaluate_policy(policy_test)

            if (
                np.isfinite(risk_test)
                and risk_test <= risk_budget
            ):
                found_feasible = True
                break

            lower_lambda = upper_lambda
            risk_error = (
                risk_test - risk_budget
                if np.isfinite(risk_test)
                else np.inf
            )

            if risk_error > 2.0:
                lambda_step = 1.0
            elif risk_error > 0.5:
                lambda_step = 0.5
            elif risk_error > 0.1:
                lambda_step = 0.25
            else:
                lambda_step = 0.05

            upper_lambda += lambda_step

            if upper_lambda >= self.max_lambda:
                upper_lambda = self.max_lambda
                V_test, policy_test = (
                    self.solve_lagrangian_value_iteration(upper_lambda)
                )
                cost_test, risk_test = self.evaluate_policy(policy_test)
                found_feasible = (
                    np.isfinite(risk_test)
                    and risk_test <= risk_budget
                )
                break

        if not found_feasible:
            return CMDPResult(
                V=V_test,
                policy=policy_test,
                lambda_value=upper_lambda,
                expected_cost=cost_test,
                expected_risk=risk_test,
                constraint_satisfied=False,
            )

        best_V = V_test
        best_policy = policy_test
        best_lambda = upper_lambda
        best_cost = cost_test
        best_risk = risk_test

        for _ in range(self.max_lambda_iterations):
            mid_lambda = (lower_lambda + upper_lambda) / 2.0

            V_mid, policy_mid = (
                self.solve_lagrangian_value_iteration(mid_lambda)
            )
            cost_mid, risk_mid = self.evaluate_policy(policy_mid)

            if (
                np.isfinite(risk_mid)
                and risk_mid <= risk_budget
            ):
                upper_lambda = mid_lambda
                best_V = V_mid
                best_policy = policy_mid
                best_lambda = mid_lambda
                best_cost = cost_mid
                best_risk = risk_mid
            else:
                lower_lambda = mid_lambda

            if upper_lambda - lower_lambda < self.tolerance:
                break

        constraint_satisfied = (
            np.isfinite(best_risk)
            and best_risk <= risk_budget
        )

        return CMDPResult(
            V=best_V,
            policy=best_policy,
            lambda_value=best_lambda,
            expected_cost=best_cost,
            expected_risk=best_risk,
            constraint_satisfied=constraint_satisfied,
        )


# ---------------------------------------------------------------------------
# STEP 11B — FOLLOW POLICY / EXTRACT PATH
# ---------------------------------------------------------------------------

def extract_cmdp_path(
    solver: CMDPSolver,
    policy: np.ndarray,
) -> PathResult:
    """Follow the policy until goal, invalid action, or loop."""
    current_state = solver.start
    path_grid = [current_state]
    visited_states = set()

    max_path_length = solver.grid_width * solver.grid_height
    reached_goal = False

    for _ in range(max_path_length):
        if current_state == solver.goal:
            reached_goal = True
            break

        if current_state in visited_states:
            break

        visited_states.add(current_state)

        x, y = current_state
        action_id = int(policy[x, y])

        if action_id < 0:
            break

        next_state = transition(
            solver.terrain,
            current_state,
            action_id,
        )

        if next_state is None:
            break

        current_state = next_state
        path_grid.append(current_state)

    path_world = np.asarray(
        [
            (
                *grid_to_world(solver.terrain, x, y),
                solver.terrain.height_grid[x, y],
            )
            for x, y in path_grid
        ],
        dtype=np.float64,
    )

    total_path_length = 0.0
    if len(path_world) > 1:
        total_path_length = float(
            np.linalg.norm(
                np.diff(path_world, axis=0),
                axis=1,
            ).sum()
        )

    return PathResult(
        path_grid=path_grid,
        path_world=path_world,
        reached_goal=reached_goal,
        total_path_length=total_path_length,
    )


def save_path_world(
    path_result: PathResult,
    csv_path: Path,
) -> None:
    """Save the CMDP world-coordinate path for later simulation."""
    np.savetxt(
        csv_path,
        path_result.path_world,
        delimiter=",",
        header="x,y,z",
        comments="",
    )


