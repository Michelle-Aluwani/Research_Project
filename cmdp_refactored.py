def check_obj(
    obj_path: Path,
    expected_size: Optional[float] = None,
    tolerance: float = 2.0,
) -> Dict:
    """Load an OBJ and return geometry/bounds information.

    This replaces the notebook's exploratory OBJ-check cell. It raises
    immediately for unusable geometry instead of printing diagnostics.
    """
    import trimesh

    obj_path = Path(obj_path)
    if not obj_path.exists():
        raise FileNotFoundError(obj_path)

    scene = trimesh.load(obj_path, force="scene", process=False)

    if isinstance(scene, trimesh.Trimesh):
        meshes = [scene]
    else:
        meshes = [
            geometry
            for geometry in scene.geometry.values()
            if isinstance(geometry, trimesh.Trimesh)
        ]

    if not meshes:
        raise ValueError("OBJ contains no usable mesh geometry.")

    combined = trimesh.util.concatenate(meshes)

    if len(combined.vertices) == 0 or len(combined.faces) == 0:
        raise ValueError("OBJ contains empty geometry.")

    if not np.isfinite(combined.vertices).all():
        raise ValueError("OBJ contains non-finite vertex coordinates.")

    bounds = combined.bounds
    min_xyz = bounds[0]
    max_xyz = bounds[1]
    size_xyz = max_xyz - min_xyz

    result = {
        "mesh_count": len(meshes),
        "vertex_count": len(combined.vertices),
        "face_count": len(combined.faces),
        "bounds": {
            "min_x": float(min_xyz[0]),
            "max_x": float(max_xyz[0]),
            "min_y": float(min_xyz[1]),
            "max_y": float(max_xyz[1]),
            "min_z": float(min_xyz[2]),
            "max_z": float(max_xyz[2]),
        },
        "size_m": {
            "x": float(size_xyz[0]),
            "y": float(size_xyz[1]),
            "z": float(size_xyz[2]),
        },
        "approximately_expected_size": (
            None
            if expected_size is None
            else (
                abs(size_xyz[0] - expected_size) <= tolerance
                and abs(size_xyz[1] - expected_size) <= tolerance
            )
        ),
    }

    return result


def classify_obj_group(name: str) -> Optional[str]:
    """Map an OBJ object/group name to rock / mud / water / wall (or None)."""
    lowered = name.lower()
    if "wall" in lowered:
        return "wall"
    if "water" in lowered:
        return "water"
    if "mud" in lowered:
        return "mud"
    if "rock" in lowered:
        return "rock"
    return None


def read_obj_groups(obj_path: Path):
    """Parse an OBJ by object name.

    Returns ``(vertices, groups, info)`` where

    * ``vertices`` is an (N, 3) float64 array in a **Z-up** frame,
    * ``groups`` maps each OBJ object name to an (M, 3) int array of
      triangle vertex indices (polygons are fan-triangulated),
    * ``info`` has ``up_axis_in_file`` ("Z" or "Y") and ``converted``.

    Blender's default OBJ export is Y-up. The rock surface is a flat
    heightfield, so the axis along which the rock mesh is thinnest is the
    vertical axis. If that is Y, every vertex is rotated (x, y, z) ->
    (x, -z, y), which is exactly what a Z-up export would have produced.
    """
    obj_path = Path(obj_path)
    if not obj_path.is_file():
        raise FileNotFoundError(obj_path)

    vertices = []
    raw_faces: Dict[str, List[Tuple[int, int, int]]] = {}
    current = "default"

    with open(obj_path, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            if not line or line[0] not in "vofg":
                continue
            parts = line.split()
            if not parts:
                continue
            tag = parts[0]
            if tag == "v":
                vertices.append(
                    (float(parts[1]), float(parts[2]), float(parts[3]))
                )
            elif tag in ("o", "g"):
                if len(parts) >= 2:
                    current = parts[1]
            elif tag == "f":
                idx = []
                for token in parts[1:]:
                    i = int(token.split("/")[0])
                    idx.append(i - 1 if i > 0 else len(vertices) + i)
                if len(idx) >= 3:
                    bucket = raw_faces.setdefault(current, [])
                    for k in range(1, len(idx) - 1):
                        bucket.append((idx[0], idx[k], idx[k + 1]))

    if not vertices:
        raise ValueError(f"{obj_path.name}: OBJ contains no vertices.")

    vertices = np.asarray(vertices, dtype=np.float64)
    groups = {
        name: np.asarray(faces, dtype=np.int64)
        for name, faces in raw_faces.items()
        if faces
    }

    rock_names = [n for n in groups if classify_obj_group(n) == "rock"]
    if not rock_names:
        raise ValueError(
            f"{obj_path.name}: no rock object found. Objects present: "
            f"{sorted(groups)}. Name the ground object 'terrain_rock'."
        )

    rock_faces = np.concatenate([groups[n] for n in rock_names])
    rock_vertices = vertices[np.unique(rock_faces)]
    extent = rock_vertices.max(axis=0) - rock_vertices.min(axis=0)
    vertical = int(np.argmin(extent))

    if vertical == 2:
        info = {"up_axis_in_file": "Z", "converted": False}
    elif vertical == 1:
        vertices = np.column_stack(
            (vertices[:, 0], -vertices[:, 2], vertices[:, 1])
        )
        info = {"up_axis_in_file": "Y", "converted": True}
    else:
        raise ValueError(
            f"{obj_path.name}: the rock mesh is thinnest along X "
            f"(extent {extent.round(2).tolist()}); cannot determine the "
            "up axis. Re-export from Blender with Up = Z."
        )

    return vertices, groups, info


def group_faces_by_type(groups: Dict[str, np.ndarray]) -> Dict[str, np.ndarray]:
    """Concatenate all OBJ objects of the same type (rock/mud/water/wall)."""
    by_type: Dict[str, List[np.ndarray]] = {
        "rock": [], "mud": [], "water": [], "wall": []
    }
    for name, faces in groups.items():
        kind = classify_obj_group(name)
        if kind is not None:
            by_type[kind].append(faces)
    return {
        kind: np.concatenate(parts)
        for kind, parts in by_type.items()
        if parts
    }


def _load_terrain_meshes(obj_path: Path) -> Dict[str, object]:
    """Return one trimesh per terrain type: rock (required), mud, water,
    wall (all optional)."""
    import trimesh

    vertices, groups, info = read_obj_groups(Path(obj_path))
    faces_by_type = group_faces_by_type(groups)

    meshes = {}
    for kind, faces in faces_by_type.items():
        meshes[kind] = trimesh.Trimesh(
            vertices=vertices, faces=faces, process=False
        )
    meshes["_info"] = info
    return meshes


def _raycast_surface(
    mesh,
    sample_x: np.ndarray,
    sample_y: np.ndarray,
    max_z: float,
    chunk_size: int,
) -> np.ndarray:
    """Raycast vertically downward and return the first surface height."""
    num_samples = len(sample_x)
    heights = np.full(num_samples, -np.inf, dtype=np.float64)
    ray_start_z = max_z + 10.0

    for start in range(0, num_samples, chunk_size):
        end = min(start + chunk_size, num_samples)

        origins = np.column_stack(
            (
                sample_x[start:end],
                sample_y[start:end],
                np.full(end - start, ray_start_z),
            )
        )

        directions = np.zeros_like(origins)
        directions[:, 2] = -1.0

        locations, index_ray, _ = mesh.ray.intersects_location(
            ray_origins=origins,
            ray_directions=directions,
            multiple_hits=False,
        )

        if len(index_ray):
            heights[start + index_ray] = locations[:, 2]

    return heights


def generate_terrain_grid(
    obj_path: Path,
    json_path: Optional[Path] = None,
    resolution: float = 0.5,
    samples_per_side: int = 5,
    chunk_size: int = 100_000,
) -> TerrainData:
    """Generate the terrain grid from the OBJ.

    Preserves the notebook's:
    - 5x5 samples/cell
    - downward +Z-to--Z raycasting convention
    - highest exposed surface wins
    - water-over-mud rule
    - majority surface coverage classification
    """
    if samples_per_side < 1:
        raise ValueError("samples_per_side must be >= 1.")

    meshes = _load_terrain_meshes(Path(obj_path))
    obj_info = meshes.pop("_info")
    wall_mesh = meshes.pop("wall", None)

    # Grid bounds come from the ground meshes only (as before), so adding
    # walls does not move the grid. Wall cells are overlaid on it.
    bounds = np.array([mesh.bounds for mesh in meshes.values()])
    min_x = float(np.min(bounds[:, 0, 0]))
    min_y = float(np.min(bounds[:, 0, 1]))
    min_z = float(np.min(bounds[:, 0, 2]))
    max_z = float(np.max(bounds[:, 1, 2]))

    nx = int(np.ceil((np.max(bounds[:, 1, 0]) - min_x) / resolution))
    ny = int(np.ceil((np.max(bounds[:, 1, 1]) - min_y) / resolution))

    offsets = (np.arange(samples_per_side) + 0.5) / samples_per_side

    # Equivalent to the notebook's cell-centre sample layout, but without
    # retaining unnecessary 4-D intermediate arrays.
    ix = np.arange(nx)[:, None, None, None]
    iy = np.arange(ny)[None, :, None, None]
    ox = offsets[None, None, :, None]
    oy = offsets[None, None, None, :]

    sample_x = (
        min_x + (ix + ox) * resolution
    )
    sample_y = (
        min_y + (iy + oy) * resolution
    )

    sample_x = np.broadcast_to(
        sample_x, (nx, ny, samples_per_side, samples_per_side)
    ).reshape(-1)
    sample_y = np.broadcast_to(
        sample_y, (nx, ny, samples_per_side, samples_per_side)
    ).reshape(-1)

    # Wall tops are ~12 m high, so ray start height must clear them.
    ray_max_z = max_z
    if wall_mesh is not None:
        ray_max_z = max(ray_max_z, float(wall_mesh.bounds[1, 2]))

    surface_heights = {}
    for terrain_name in ("rock", "mud", "water"):
        if terrain_name in meshes:
            surface_heights[terrain_name] = _raycast_surface(
                meshes[terrain_name],
                sample_x,
                sample_y,
                ray_max_z,
                chunk_size,
            )
        else:
            # Optional layer (e.g. a terrain with no water): never hit.
            surface_heights[terrain_name] = np.full(
                len(sample_x), -np.inf, dtype=np.float64
            )

    if wall_mesh is not None:
        wall_hit = np.isfinite(
            _raycast_surface(
                wall_mesh, sample_x, sample_y, ray_max_z, chunk_size
            )
        ).reshape(nx, ny, samples_per_side, samples_per_side)
    else:
        wall_hit = np.zeros(
            (nx, ny, samples_per_side, samples_per_side), dtype=bool
        )

    surface_stack = np.vstack(
        (
            surface_heights["rock"],
            surface_heights["mud"],
            surface_heights["water"],
        )
    )

    sample_types = np.argmax(surface_stack, axis=0)
    sample_heights = np.max(surface_stack, axis=0)
    valid_samples = np.isfinite(sample_heights)

    sample_type_grid = sample_types.reshape(
        nx, ny, samples_per_side, samples_per_side
    )
    sample_height_grid = sample_heights.reshape(
        nx, ny, samples_per_side, samples_per_side
    )
    valid_grid = valid_samples.reshape(
        nx, ny, samples_per_side, samples_per_side
    )

    cell_types = np.zeros((nx, ny), dtype=np.int8)
    cell_heights = np.full((nx, ny), np.nan, dtype=np.float64)
    cell_coverage = np.zeros((nx, ny), dtype=np.float64)

    for x in range(nx):
        for y in range(ny):
            types = sample_type_grid[x, y].reshape(-1)
            heights = sample_height_grid[x, y].reshape(-1)
            valid = valid_grid[x, y].reshape(-1)

            # Wall cell: most of the cell's samples hit a wall mesh. The
            # stored height is the GROUND height under the wall, never the
            # ~12 m wall top, so slope/roughness of neighbouring cells stay
            # meaningful.
            wall_fraction = float(np.mean(wall_hit[x, y]))
            if wall_fraction > 0.5:
                cell_types[x, y] = WALL_ID
                cell_coverage[x, y] = wall_fraction
                if np.any(valid):
                    cell_heights[x, y] = np.mean(heights[valid])
                continue

            if not np.any(valid):
                continue

            valid_types = types[valid]
            counts = np.bincount(valid_types, minlength=3)
            winning_type = int(np.argmax(counts))
            winning = valid & (types == winning_type)

            cell_types[x, y] = winning_type
            cell_heights[x, y] = np.mean(heights[winning])
            cell_coverage[x, y] = counts[winning_type] / len(valid_types)

    terrain = TerrainData(
        grid=cell_types,
        height_grid=cell_heights,
        coverage_grid=cell_coverage,
        resolution=float(resolution),
        bounds={
            "min_x": min_x,
            "max_x": float(np.max(bounds[:, 1, 0])),
            "min_y": min_y,
            "max_y": float(np.max(bounds[:, 1, 1])),
            "min_z": min_z,
            "max_z": max_z,
        },
    )

    if json_path is not None:
        save_terrain_grid(
            terrain, Path(json_path), samples_per_side, obj_info=obj_info
        )

    return terrain


def load_terrain_grid(json_path: Path) -> TerrainData:
    """Load the terrain representation produced by the notebook."""
    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    metadata = data["metadata"]
    grid = np.asarray(data["grid"], dtype=np.int8)
    height_grid = np.asarray(
        [
            [np.nan if value is None else value for value in row]
            for row in data["height_grid"]
        ],
        dtype=np.float64,
    )
    coverage_grid = np.asarray(
        data.get(
            "coverage_grid",
            np.ones_like(grid, dtype=np.float64),
        ),
        dtype=np.float64,
    )

    expected_shape = (
        int(metadata["grid_width"]),
        int(metadata["grid_height"]),
    )
    if grid.shape != expected_shape:
        raise ValueError(
            f"Grid shape {grid.shape} does not match metadata {expected_shape}."
        )

    return TerrainData(
        grid=grid,
        height_grid=height_grid,
        coverage_grid=coverage_grid,
        resolution=float(metadata["resolution_m"]),
        bounds=dict(metadata["bounds_m"]),
    )


def save_terrain_grid(
    terrain: TerrainData,
    json_path: Path,
    samples_per_side: int = 5,
    obj_info: Optional[Dict] = None,
) -> None:
    """Save terrain data using the notebook's JSON structure."""
    height_grid_json = [
        [
            None if not np.isfinite(value) else float(value)
            for value in row
        ]
        for row in terrain.height_grid
    ]

    data = {
        "metadata": {
            "resolution_m": terrain.resolution,
            "grid_width": terrain.nx,
            "grid_height": terrain.ny,
            "total_cells": terrain.nx * terrain.ny,
            "coordinate_system": {
                "x": "horizontal",
                "y": "horizontal",
                "z": "height",
                "up_axis": "Z",
                "surface_direction": "+Z",
            },
            "schema_version": TERRAIN_GRID_SCHEMA_VERSION,
            "obj_info": obj_info or {},
            "terrain_types": {
                "0": "rock",
                "1": "mud",
                "2": "water",
                "3": "wall",
            },
            "bounds_m": terrain.bounds,
            "classification": {
                "method": "majority_surface_coverage",
                "samples_per_cell": samples_per_side**2,
                "sample_layout": f"{samples_per_side}x{samples_per_side}",
                "surface_rule": "highest_exposed_surface_wins",
                "water_over_mud": True,
                "wall_rule": "majority_of_samples_hit_wall_mesh; "
                             "height_grid keeps ground height under walls",
            },
        },
        "grid": terrain.grid.tolist(),
        "height_grid": height_grid_json,
        "coverage_grid": terrain.coverage_grid.tolist(),
    }

    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)


