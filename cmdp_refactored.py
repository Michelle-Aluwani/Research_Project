def prepare_risk_model(
    terrain: TerrainData,
    wall_slope_threshold: float = 45.0,
    risk_weights: Sequence[float] = DEFAULT_RISK_WEIGHTS,
) -> RiskFeatures:
    """Run Steps 3-8 as one reusable preprocessing operation."""
    slope_deg = calculate_slope(terrain)
    roughness_grid = calculate_roughness(terrain)
    terrain_risk_grid = calculate_terrain_risk(terrain)
    clearance_grid = calculate_clearance(
        terrain,
        slope_deg,
        wall_slope_threshold,
    )

    features = calculate_risk_features(
        terrain,
        slope_deg,
        roughness_grid,
        terrain_risk_grid,
        clearance_grid,
    )
    calculate_weighted_risk(features, risk_weights)
    return features


# ---------------------------------------------------------------------------
# ONE EXPERIMENT
# ---------------------------------------------------------------------------

def run_experiment(
    terrain: TerrainData,
    start: GridState,
    goal: GridState,
    risk_budget: float,
    risk_weights: Sequence[float] = DEFAULT_RISK_WEIGHTS,
    wall_slope_threshold: float = 45.0,
    output_path: Optional[Path] = None,
    backend: str = "auto",
    device: Optional[str] = None,
    path_output: Optional[Path] = None,
) -> Dict:
    """Run Steps 3-11C for one terrain/scenario/D condition.

    If ``path_output`` is given, the world-coordinate path CSV is written
    from the SAME solve (the CLI used to solve a second time).
    """
    features = prepare_risk_model(
        terrain,
        wall_slope_threshold=wall_slope_threshold,
        risk_weights=risk_weights,
    )

    solver = CMDPSolver(
        terrain=terrain,
        weighted_risk_grid=features.weighted_risk_grid,
        start=start,
        goal=goal,
        backend=backend,
        device=device,
    )

    cmdp_result = solver.solve_constrained_cmdp(risk_budget)
    path_result = extract_cmdp_path(solver, cmdp_result.policy)

    if path_output is not None and path_result.reached_goal:
        path_output = Path(path_output)
        path_output.parent.mkdir(parents=True, exist_ok=True)
        save_path_world(path_result, path_output)

    analysis = None
    if path_result.reached_goal:
        analysis = analyse_cmdp_path(
            terrain,
            features,
            features.weighted_risk_grid,
            path_result,
            risk_budget,
        )

    result = {
        "start": list(start),
        "goal": list(goal),
        "risk_budget": float(risk_budget),
        "lambda": float(cmdp_result.lambda_value),
        "expected_cost": float(cmdp_result.expected_cost),
        "expected_risk": float(cmdp_result.expected_risk),
        "constraint_satisfied": bool(cmdp_result.constraint_satisfied),
        "reached_goal": bool(path_result.reached_goal),
        "path_states": len(path_result.path_grid),
        "path_length_m": float(path_result.total_path_length),
        "analysis": analysis,
        "solver_backend": solver.backend,
        "solver_device": solver.device,
    }

    if output_path is not None:
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(result, f, indent=2)

    return result


