# STEP 11C — PATH ANALYSIS
# ---------------------------------------------------------------------------

def analyse_cmdp_path(
    terrain: TerrainData,
    features: RiskFeatures,
    weighted_risk_grid: np.ndarray,
    path_result: PathResult,
    risk_budget: float,
) -> Dict:
    """Return structured statistics for a successful CMDP path."""
    if not path_result.path_grid:
        raise ValueError("CMDP path is empty.")
    if not path_result.reached_goal:
        raise ValueError("CMDP path did not reach the goal.")

    path_grid = path_result.path_grid

    terrain_ids = np.asarray(
        [terrain.grid[x, y] for x, y in path_grid],
        dtype=np.int8,
    )

    counts = {
        name: int(np.sum(terrain_ids == terrain_id))
        for terrain_id, name in TERRAIN_NAMES.items()
    }

    entries = {name: 0 for name in TERRAIN_NAMES.values()}
    for previous, current in zip(terrain_ids[:-1], terrain_ids[1:]):
        if current != previous:
            entries[TERRAIN_NAMES[int(current)]] += 1

    path_risks = np.asarray(
        [weighted_risk_grid[x, y] for x, y in path_grid],
        dtype=np.float64,
    )

    if not np.isfinite(path_risks).all():
        raise ValueError("Path contains invalid risk values.")

    accumulated_risk = float(np.sum(path_risks))
    risk_remaining = float(risk_budget - accumulated_risk)

    path_slope = np.asarray(
        [features.slope_deg[x, y] for x, y in path_grid]
    )
    path_roughness = np.asarray(
        [features.roughness_grid[x, y] for x, y in path_grid]
    )
    path_clearance = np.asarray(
        [features.clearance_grid[x, y] for x, y in path_grid]
    )
    path_clearance_risk = np.asarray(
        [features.C_risk[x, y] for x, y in path_grid]
    )

    valid_risks = weighted_risk_grid[
        np.isfinite(weighted_risk_grid)
    ]
    high_risk_threshold = float(np.percentile(valid_risks, 90))
    high_risk_count = int(np.sum(path_risks >= high_risk_threshold))

    return {
        "states": len(path_grid),
        "movements": max(0, len(path_grid) - 1),
        "path_length_m": path_result.total_path_length,
        "terrain_counts": counts,
        "terrain_entries": entries,
        "accumulated_risk": accumulated_risk,
        "mean_path_risk": float(np.mean(path_risks)),
        "maximum_path_risk": float(np.max(path_risks)),
        "maximum_slope_deg": float(np.nanmax(path_slope)),
        "maximum_roughness_m": float(np.nanmax(path_roughness)),
        "minimum_clearance_m": float(np.nanmin(path_clearance)),
        "maximum_clearance_risk": float(np.nanmax(path_clearance_risk)),
        "risk_budget": float(risk_budget),
        "risk_remaining": risk_remaining,
        "risk_budget_satisfied": bool(accumulated_risk <= risk_budget),
        "high_risk_threshold": high_risk_threshold,
        "high_risk_states": high_risk_count,
        "high_risk_percentage": float(
            100.0 * high_risk_count / len(path_grid)
        ),
    }


