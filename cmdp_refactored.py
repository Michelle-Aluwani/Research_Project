def get_state(terrain: TerrainData, x: int, y: int) -> Optional[Dict]:
    """Return state information or None if outside the grid."""
    if not (0 <= x < terrain.nx and 0 <= y < terrain.ny):
        return None

    terrain_id = int(terrain.grid[x, y])
    return {
        "x": x,
        "y": y,
        "terrain_id": terrain_id,
        "terrain": TERRAIN_NAMES[terrain_id],
    }


def get_neighbours(terrain: TerrainData, x: int, y: int) -> List[GridState]:
    """Return valid 8-connected neighbouring states."""
    neighbours = []
    for dx, dy in ACTIONS.values():
        nx = x + dx
        ny = y + dy
        if 0 <= nx < terrain.nx and 0 <= ny < terrain.ny:
            neighbours.append((nx, ny))
    return neighbours


def grid_to_world(
    terrain: TerrainData,
    x: int,
    y: int,
) -> Tuple[float, float]:
    """Convert grid indices to cell-centre world X/Y coordinates."""
    return (
        terrain.bounds["min_x"] + (x + 0.5) * terrain.resolution,
        terrain.bounds["min_y"] + (y + 0.5) * terrain.resolution,
    )


# ---------------------------------------------------------------------------
# STEP 2 — ACTIONS / TRANSITIONS / MOVEMENT COST
# ---------------------------------------------------------------------------

def transition(
    terrain: TerrainData,
    state: GridState,
    action_id: int,
) -> Optional[GridState]:
    """Apply an action; invalid/out-of-bounds/no-surface moves return None."""
    x, y = state
    dx, dy = ACTIONS[action_id]
    next_x = x + dx
    next_y = y + dy

    if not (0 <= next_x < terrain.nx and 0 <= next_y < terrain.ny):
        return None

    if not np.isfinite(terrain.height_grid[next_x, next_y]):
        return None

    return next_x, next_y


def movement_cost_3d(
    terrain: TerrainData,
    state: GridState,
    action_id: int,
) -> float:
    """Notebook Step 2's 3-D Euclidean movement cost."""
    next_state = transition(terrain, state, action_id)
    if next_state is None:
        return np.inf

    x1, y1 = state
    x2, y2 = next_state

    z1 = terrain.height_grid[x1, y1]
    z2 = terrain.height_grid[x2, y2]

    if not np.isfinite(z1) or not np.isfinite(z2):
        return np.inf

    dx = (x2 - x1) * terrain.resolution
    dy = (y2 - y1) * terrain.resolution
    dz = z2 - z1

    return float(np.sqrt(dx * dx + dy * dy + dz * dz))


# ---------------------------------------------------------------------------
# STEP 3 — SLOPE
# ---------------------------------------------------------------------------

def calculate_slope(terrain: TerrainData) -> np.ndarray:
    """Calculate slope in degrees while preserving invalid cells as NaN."""
    height_grid = terrain.height_grid
    valid = np.isfinite(height_grid)

    height_for_gradient = height_grid.copy()
    if np.any(~valid):
        if not np.any(valid):
            return np.full_like(height_grid, np.nan, dtype=np.float64)
        height_for_gradient[~valid] = np.nanmean(height_grid)

    dz_dx, dz_dy = np.gradient(
        height_for_gradient,
        terrain.resolution,
        axis=(0, 1),
    )

    slope_deg = np.degrees(
        np.arctan(np.sqrt(dz_dx**2 + dz_dy**2))
    )
    slope_deg[~valid] = np.nan
    # Wall cells have no terrain risk; keep them out of the normalisation.
    slope_deg[terrain.wall_mask] = np.nan
    return slope_deg


# ---------------------------------------------------------------------------
# STEP 4 — ROUGHNESS
# ---------------------------------------------------------------------------

def calculate_roughness(terrain: TerrainData) -> np.ndarray:
    """Calculate 3x3 neighbourhood height standard deviation."""
    height_grid = terrain.height_grid
    nx, ny = terrain.shape

    roughness = np.full_like(height_grid, np.nan, dtype=np.float64)

    for x in range(nx):
        for y in range(ny):
            if not np.isfinite(height_grid[x, y]):
                continue

            x_min = max(0, x - 1)
            x_max = min(nx, x + 2)
            y_min = max(0, y - 1)
            y_max = min(ny, y + 2)

            neighbourhood = height_grid[x_min:x_max, y_min:y_max]
            valid = neighbourhood[np.isfinite(neighbourhood)]

            if len(valid) >= 2:
                roughness[x, y] = np.std(valid)

    roughness[terrain.wall_mask] = np.nan
    return roughness


# ---------------------------------------------------------------------------
# STEP 5 — TERRAIN TYPE RISK
# ---------------------------------------------------------------------------

def calculate_terrain_risk(
    terrain: TerrainData,
    terrain_risk_values: Optional[Dict[int, float]] = None,
) -> np.ndarray:
    """Map terrain IDs to the supplied terrain-risk values."""
    risk_values = (
        TERRAIN_RISK_VALUES
        if terrain_risk_values is None
        else terrain_risk_values
    )

    terrain_risk = np.full(
        terrain.shape,
        np.nan,
        dtype=np.float64,
    )

    for terrain_id, risk in risk_values.items():
        terrain_risk[terrain.grid == terrain_id] = risk

    return terrain_risk


# ---------------------------------------------------------------------------
# STEP 6 — CLEARANCE
# ---------------------------------------------------------------------------

def calculate_clearance(
    terrain: TerrainData,
    slope_deg: np.ndarray,
    wall_slope_threshold: float = 45.0,
) -> np.ndarray:
    """Distance (m) to the nearest obstacle cell.

    Obstacle cells are (a) real wall cells (grid id 3) and (b) steep
    wall-like terrain cells with slope >= ``wall_slope_threshold``.
    Wall cells themselves get NaN clearance (they are not traversable).
    """
    from scipy.ndimage import distance_transform_edt

    real_walls = terrain.wall_mask
    valid = np.isfinite(terrain.height_grid) & ~real_walls

    steep_cells = (
        valid
        & np.isfinite(slope_deg)
        & (slope_deg >= wall_slope_threshold)
    )
    obstacle_cells = steep_cells | real_walls

    if np.any(obstacle_cells):
        clearance = distance_transform_edt(
            ~obstacle_cells,
            sampling=terrain.resolution,
        )
    else:
        clearance = np.full(terrain.shape, np.inf, dtype=np.float64)

    clearance[~valid] = np.nan
    return clearance


# ---------------------------------------------------------------------------
# STEP 7 — NORMALIZED RISK FEATURES
# ---------------------------------------------------------------------------

def normalize_risk(grid: np.ndarray) -> np.ndarray:
    """Min-max normalize finite values to [0, 1]."""
    result = np.full_like(grid, np.nan, dtype=np.float64)
    valid = np.isfinite(grid)

    if not np.any(valid):
        return result

    minimum = np.min(grid[valid])
    maximum = np.max(grid[valid])

    if maximum == minimum:
        result[valid] = 0.0
    else:
        result[valid] = (
            (grid[valid] - minimum)
            / (maximum - minimum)
        )

    return result


def calculate_risk_features(
    terrain: TerrainData,
    slope_deg: np.ndarray,
    roughness_grid: np.ndarray,
    terrain_risk_grid: np.ndarray,
    clearance_grid: np.ndarray,
) -> RiskFeatures:
    """Create S, R, T and C risk components."""
    S_risk = normalize_risk(slope_deg)
    R_risk = normalize_risk(roughness_grid)
    T_risk = terrain_risk_grid.copy()

    C_risk_raw = np.full_like(
        clearance_grid,
        np.nan,
        dtype=np.float64,
    )

    valid_clearance = np.isfinite(clearance_grid)
    positive_clearance = (
        valid_clearance & (clearance_grid > 0)
    )

    C_risk_raw[positive_clearance] = (
        1.0 / clearance_grid[positive_clearance]
    ) + 1.0

    zero_clearance = (
        valid_clearance & (clearance_grid <= 0)
    )

    if np.any(positive_clearance):
        max_clearance_risk = np.max(
            C_risk_raw[positive_clearance]
        )
        C_risk_raw[zero_clearance] = max_clearance_risk

    C_risk = normalize_risk(C_risk_raw)

    valid_features = (
        np.isfinite(S_risk)
        & np.isfinite(R_risk)
        & np.isfinite(T_risk)
        & np.isfinite(C_risk)
    )

    return RiskFeatures(
        slope_deg=slope_deg,
        roughness_grid=roughness_grid,
        terrain_risk_grid=terrain_risk_grid,
        clearance_grid=clearance_grid,
        S_risk=S_risk,
        R_risk=R_risk,
        T_risk=T_risk,
        C_risk=C_risk,
        weighted_risk_grid=np.full(
            terrain.shape, np.nan, dtype=np.float64
        ),
        valid_risk_features=valid_features,
    )


# ---------------------------------------------------------------------------
# STEP 8 — WEIGHTED RISK
# ---------------------------------------------------------------------------

def calculate_weighted_risk(
    features: RiskFeatures,
    weights: Sequence[float] = DEFAULT_RISK_WEIGHTS,
) -> np.ndarray:
    """Calculate d(x,a) from the four risk components."""
    weights = np.asarray(weights, dtype=np.float64)
    if weights.shape != (4,):
        raise ValueError("Exactly four risk weights are required.")
    if not np.isclose(np.sum(weights), 1.0):
        raise ValueError("Risk weights must sum to 1.0.")

    S_risk, R_risk, T_risk, C_risk = (
        features.S_risk,
        features.R_risk,
        features.T_risk,
        features.C_risk,
    )

    valid = (
        np.isfinite(S_risk)
        & np.isfinite(R_risk)
        & np.isfinite(T_risk)
        & np.isfinite(C_risk)
    )

    weighted = np.full(
        S_risk.shape,
        np.nan,
        dtype=np.float64,
    )

    weighted[valid] = (
        weights[0] * S_risk[valid]
        + weights[1] * R_risk[valid]
        + weights[2] * T_risk[valid]
        + weights[3] * C_risk[valid]
    )

    # Keep invalid/no-surface cells non-traversable.
    # The supplied notebook assigned 0.0 here but Step 11A's finite-value
    # check treats finite values as traversable, so 0.0 would contradict
    # the notebook's stated invalid-terrain rule.
    weighted[~features.valid_risk_features] = np.nan

    features.weighted_risk_grid = weighted
    return weighted


# ---------------------------------------------------------------------------
# STEP 9 — STOCHASTIC TRANSITIONS
# ---------------------------------------------------------------------------

def success_probability(
    terrain: TerrainData,
    weighted_risk_grid: np.ndarray,
    x: int,
    y: int,
    action_id: int,
) -> float:
    """p_success = 1 - destination risk."""
    next_state = transition(terrain, (x, y), action_id)
    if next_state is None:
        return 0.0

    nx, ny = next_state
    risk = weighted_risk_grid[nx, ny]

    if not np.isfinite(risk):
        return 0.0

    return float(np.clip(1.0 - risk, 0.0, 1.0))


def stochastic_transition(
    terrain: TerrainData,
    weighted_risk_grid: np.ndarray,
    x: int,
    y: int,
    action_id: int,
) -> List[Tuple[GridState, float]]:
    """Return success-to-neighbour and failure-self-loop outcomes."""
    next_state = transition(terrain, (x, y), action_id)
    if next_state is None:
        return []

    p_success = success_probability(
        terrain,
        weighted_risk_grid,
        x,
        y,
        action_id,
    )
    p_failure = 1.0 - p_success

    outcomes = []
    if p_success > 0.0:
        outcomes.append((next_state, p_success))
    if p_failure > 0.0:
        outcomes.append(((x, y), p_failure))

    return outcomes


